"""Turns a finished run into report-ready material: markdown tables + figures + an auto-filled
results section (outputs/<run>/report/RESULTS.md) that you paste into the project report / slides.
Numbers are NEVER typed by hand - re-run and everything regenerates."""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

from forecastkit.evaluation.evaluator import Evaluator
from forecastkit.viz.plots import make_all_figures

NICE = {"MAE": "MAE", "RMSE": "RMSE", "WAPE": "WAPE", "pinball": "Pinball", "WQL": "wQL", "cov80": "Cov80",
        "cov90": "Cov90", "width80": "Width80", "width90": "Width90"}


def md_table(df: pd.DataFrame, digits=3, index=True) -> str:
    d = df.copy()
    if index:
        d = d.reset_index()
    cols = [str(c) for c in d.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    best = {}
    for c in d.columns:
        if c in ("MAE", "RMSE", "WAPE", "pinball", "WQL") and pd.api.types.is_numeric_dtype(d[c]):
            best[c] = d[c].min()
    for _, r in d.iterrows():
        cells = []
        for c in d.columns:
            v = r[c]
            if isinstance(v, (float, np.floating)):
                s = "—" if np.isnan(v) else f"{v:.{digits}f}"
                if c in best and not np.isnan(v) and np.isclose(v, best[c]):
                    s = f"**{s}**"
            else:
                s = str(v)
            cells.append(s)
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def _cols(df, cols):
    return df[[c for c in cols if c in df.columns]]


def build_report(cfg: dict, run_dir, fan_models=None) -> Path:
    run_dir = Path(run_dir)
    ev = Evaluator(cfg, run_dir)
    tables = ev.all_tables()
    out = run_dir / "report"
    out.mkdir(parents=True, exist_ok=True)
    figs = make_all_figures(ev, run_dir, out / "figures", fan_models)
    ds, o = ev.ds, ev.origins
    cls = ev.info.loc[~ev.cold, "intermittency"].value_counts().to_dict()
    n_cens = ev.C[:, ~ev.cold].sum() / max(ev.A[:, ~ev.cold].sum(), 1)
    stock = cfg.get("masks", {}).get("stockout", {}) or {}
    lines = []
    A = lines.append
    A(f"# Results — run `{cfg['run_name']}`\n")
    A("> Auto-generated by `forecastkit report`. Do not edit by hand; re-run to refresh.\n")
    A("## 1. Setup\n")
    A(f"- **Dataset**: `{ds.name}` ({ds.meta.get('source', 'n/a')}) — {ds.N} series ({int(ev.cold.sum())} held out as simulated "
      f"cold-start), {ds.T} days {ds.dates[0].date()} → {ds.dates[-1].date()}, {len(ds.known_names)} known-future covariates")
    A(f"- **Backtest**: {len(o)} rolling origins ({', '.join(str(pd.Timestamp(x).date()) for x in o)}), horizon H={ev.H}, "
      f"step {cfg.get('backtest', {}).get('step', ev.H)} days; one earlier validation origin reserved for tuning")
    A(f"- **Models**: {', '.join(ev.models)}")
    A(f"- **Quantiles**: {ev.qs}")
    A(f"- **Series classes (established)**: {cls}")
    A(f"- **Stockout proxy**: zero runs ≥ max({stock.get('min_run', '—')} d, {stock.get('adi_multiplier', '—')}×ADI) in series "
      f"with ≥{stock.get('min_nonzero_events', '—')} sales events (a PROXY, not ground truth) → "
      f"{100 * n_cens:.1f}% of evaluated cells flagged. Models treat flagged days as missing, never imputed.")
    A("- **Point metrics**: MAE & WAPE use the median forecast; RMSE uses the mean forecast; WAPE is aggregated (Σ|e|/Σy).")
    A("- **Interval metrics**: pinball = mean over the quantile set; Cov80/Cov90 = share of actuals inside the central interval "
      "(target 0.80/0.90, inclusive bounds — generous for zero-heavy counts); Width = mean interval width.\n")

    A("## 2. Main results (established series, all days, averaged over origins)\n")
    A(md_table(_cols(tables["main_all_days"], ["MAE", "RMSE", "WAPE", "pinball", "WQL", "cov80", "width80", "cov90", "width90"])))
    A("\n### Same table on NON-censored days only (stockout-flagged days excluded)\n")
    A(md_table(_cols(tables["main_non_censored"], ["MAE", "RMSE", "WAPE", "pinball", "WQL", "cov80", "cov90"])))
    A("\n### Stability across origins (mean ± std over rolling origins)\n")
    st = tables["origin_stability"]
    stab = pd.DataFrame({"MAE": [f"{a:.3f} ± {b:.3f}" for a, b in zip(st.MAE_mean, st.MAE_std)],
                         "WAPE": [f"{a:.3f} ± {b:.3f}" for a, b in zip(st.WAPE_mean, st.WAPE_std)],
                         "Pinball": [f"{a:.3f} ± {b:.3f}" for a, b in zip(st.pinball_mean, st.pinball_std)]}, index=st.index)
    A(md_table(stab))
    A("\n## 3. By forecast horizon\n")
    bh = tables["by_horizon"]
    for mt in ("WAPE", "pinball", "cov90"):
        A(f"\n**{NICE.get(mt, mt)}**\n")
        A(md_table(bh.pivot(index="model", columns="h", values=mt)[[c for c in bh.h.unique()]].reindex(ev.models)))
    A("\n## 4. By slice (WAPE | Pinball)\n")
    bs = tables["by_slice"]
    for mt in ("WAPE", "pinball"):
        A(f"\n**{NICE.get(mt, mt)}**\n")
        A(md_table(bs.pivot(index="slice", columns="model", values=mt)[ev.models]))
    if "cold_start" in tables:
        A("\n## 5. Cold start (simulated: only the last "
          f"{ds.meta['cold_days']} days visible; item identity unknown to global models)\n")
        A(md_table(_cols(tables["cold_start"], ["MAE", "RMSE", "WAPE", "pinball", "cov90", "width90"])))
    A("\n## 6. Significance (paired bootstrap over series; negative diff = better than reference)\n")
    A(md_table(tables["significance_wape"].drop(columns=["metric"]), index=False, digits=4))
    A("\n" + md_table(tables["significance_pinball"].drop(columns=["metric"]), index=False, digits=4))
    A("\n## 7. Compute cost (all origins, seconds)\n")
    if len(tables["runtime"]):
        A(md_table(tables["runtime"], digits=1))
    A("\n## 8. Calibration (P(y ≤ q̂) vs nominal; for discrete counts the ideal lies between the strict and non-strict value)\n")
    cal = tables["calibration"]
    A(md_table(cal.pivot(index="model", columns="nominal", values="empirical").reindex(ev.models), digits=2))
    A("\n## 9. Figures\n")
    for k, p in figs.items():
        A(f"- **{k}**: `figures/{Path(p).name}`")
    (out / "RESULTS.md").write_text("\n".join(lines) + "\n")
    for name, df in tables.items():
        if df is not None and len(df):
            df.to_csv(out / f"{name}.csv")
    return out / "RESULTS.md"
